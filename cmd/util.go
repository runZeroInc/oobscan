package cmd

import "strings"

// csvFields splits a comma-separated flag value into trimmed, non-empty fields.
func csvFields(value string) []string {
	parts := strings.Split(value, ",")
	out := make([]string, 0, len(parts))
	for _, p := range parts {
		if p = strings.TrimSpace(p); p != "" {
			out = append(out, p)
		}
	}
	return out
}
