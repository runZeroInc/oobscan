// The join that matters: a MAC one BMC publishes for its server, located by a
// neighbour table a different BMC gave up. MACs are globally unique, so this must
// work across prefixes.
func TestResolveViaAnotherBMCsNeighbourCache(t *testing.T) {
	server := "198.51.100.7"
	owner := &ManagedHost{
		BMC:        "192.0.2.10",
		BMCClass:   "bmc",
		MACs:       []Value{{Value: "aa:bb:cc:11:22:33"}},
		Confidence: Identity,
	}
	witness := &ManagedHost{
		BMC:        "192.0.2.11",
		BMCClass:   "bmc",
		Neighbours: []Neighbour{{IP: server, MAC: "aa:bb:cc:11:22:33"}},
	}
	ix := NewIndex()
	ix.Observe(owner)
	ix.Observe(witness)

	if !ix.Resolve(owner) {
		t.Fatal("expected the neighbour join to resolve an address")
	}
	if len(owner.Addresses) != 1 || owner.Addresses[0].Value != server {
		t.Fatalf("addresses = %+v, want %s", owner.Addresses, server)
	}
	if owner.Confidence != Resolved {
		t.Fatalf("confidence = %q, want %q", owner.Confidence, Resolved)
	}
}

// A MAC many endpoints claim as their own is a duplicate factory address, not a
// machine. Tyan ships one such value fleet-wide and it produced a block of confident
// wrong matches before the gate existed.
func TestDuplicateFactoryMACIsGated(t *testing.T) {
	const dup = "00:e0:81:40:e0:10"
	ix := NewIndex()
	for _, a := range []string{"192.0.2.1", "192.0.2.2", "192.0.2.3", "192.0.2.4"} {
		ix.ObserveHostMAC(a, dup)
	}
	ix.Observe(&ManagedHost{BMC: "192.0.2.9", BMCClass: "bmc",
		Neighbours: []Neighbour{{IP: "198.51.100.9", MAC: dup}}})

	m := &ManagedHost{BMC: "192.0.2.20", BMCClass: "bmc",
		MACs: []Value{{Value: dup}}, Confidence: Identity}
	if ix.Resolve(m) {
		t.Fatalf("resolved on a duplicate factory MAC: %+v", m.Addresses)
	}
}

// The gate counts self-claims only. A BMC publishing its server's NIC list must not
// push that server's MAC over the threshold and gate away the join it enabled.
func TestPublicationDoesNotTripTheSelfClaimGate(t *testing.T) {
	const mac = "aa:bb:cc:44:55:66"
	ix := NewIndex()
	// Three BMCs all publish the same server MAC (a chassis with shared reporting).
	for _, b := range []string{"192.0.2.30", "192.0.2.31", "192.0.2.32"} {
		ix.Observe(&ManagedHost{BMC: b, BMCClass: "bmc", MACs: []Value{{Value: mac}}})
	}
	ix.Observe(&ManagedHost{BMC: "192.0.2.33", BMCClass: "bmc",
		Neighbours: []Neighbour{{IP: "198.51.100.44", MAC: mac}}})

	m := &ManagedHost{BMC: "192.0.2.30", BMCClass: "bmc",
		MACs: []Value{{Value: mac}}, Confidence: Identity}
	if !ix.Resolve(m) {
		t.Fatal("publication of a server MAC wrongly tripped the self-claim gate")
	}
}

// Two BMCs in a rack are not a BMC and its server.
func TestResolveNeverReturnsAnotherOOBDevice(t *testing.T) {
	const mac = "aa:bb:cc:77:88:99"
	ix := NewIndex()
	ix.Observe(&ManagedHost{BMC: "192.0.2.41", BMCClass: "bmc"})
	ix.ObserveHostMAC("192.0.2.41", mac)
	m := &ManagedHost{BMC: "192.0.2.40", BMCClass: "bmc",
		MACs: []Value{{Value: mac}}, Confidence: Identity}
	if ix.Resolve(m) {
		t.Fatalf("matched a BMC to another BMC: %+v", m.Addresses)
	}
}

// A stated address is the BMC's own claim and must not be second-guessed.
func TestResolveLeavesStatedAddressesAlone(t *testing.T) {
	ix := NewIndex()
	ix.Observe(&ManagedHost{BMC: "192.0.2.51", BMCClass: "bmc",
		Neighbours: []Neighbour{{IP: "198.51.100.99", MAC: "aa:bb:cc:00:11:22"}}})
	m := &ManagedHost{BMC: "192.0.2.50", BMCClass: "bmc",
		Addresses:  []Value{{Value: "198.51.100.5"}},
		MACs:       []Value{{Value: "aa:bb:cc:00:11:22"}},
		Confidence: Stated,
	}
	if ix.Resolve(m) {
		t.Fatal("Resolve overwrote a stated address")
	}
	if len(m.Addresses) != 1 || m.Addresses[0].Value != "198.51.100.5" {
		t.Fatalf("addresses = %+v", m.Addresses)
	}
}

func TestParseNeighboursAcceptsBareHexMACs(t *testing.T) {
	got := parseNeighbours("192.0.2.1=0007B4001C01,192.0.2.2=40:55:39:0e:1a:41,bogus")
	if len(got) != 2 {
		t.Fatalf("got %d neighbours, want 2: %+v", len(got), got)
	}
	if got[0].MAC != "00:07:b4:00:1c:01" {
		t.Fatalf("bare hex MAC = %q", got[0].MAC)
	}
}

// The adjacency hint is measured, not assumed: +6/+7 lead, and an earlier 16-host
// sample that suggested -1/-2 was unrepresentative in both rate and direction.
func TestAdjacencyHintOrdersMeasuredOffsetsFirst(t *testing.T) {
	h := Adjacency("44:a8:42:37:26:c0")
	if h == nil {
		t.Fatal("nil hint")
	}
	if h.Offsets[0] != 6 || h.Offsets[1] != 7 {
		t.Fatalf("offsets = %v, want +6/+7 first", h.Offsets[:2])
	}
	if len(h.Guesses) == 0 || h.Guesses[0] != "44:a8:42:37:26:c6" {
		t.Fatalf("guesses = %v", h.Guesses)
	}
	for _, g := range h.Guesses {
		if g[:8] != h.OUI {
			t.Fatalf("guess %q left the burned-in OUI block", g)
		}
	}
}

func TestSummarizeSeparatesDescribedFromLocated(t *testing.T) {
	hosts := []*ManagedHost{
		{BMC: "192.0.2.1", Addresses: []Value{{Value: "198.51.100.1"}}, Confidence: Stated},
		{BMC: "192.0.2.2", MACs: []Value{{Value: "aa:bb:cc:dd:ee:f0"}}, Confidence: Identity},
		{BMC: "192.0.2.3", Names: []Value{{Value: "web01"}},
			Addresses: []Value{{Value: "198.51.100.3"}}, Confidence: Resolved},
	}
	s := Summarize(hosts, 10)
	if s.OOBDevices != 10 || s.Described != 3 || s.Located != 2 || s.Stated != 1 || s.Resolved != 1 {
		t.Fatalf("summary = %+v", s)
	}
}

// The Redfish ServiceRoot UUID is the controller's identity, not the system's. ATEN
// derives it from the BMC's own NIC, so it arrives as 00000000-...-<bmc mac> and made
// every Supermicro in a scan report a managed server whose only described property was
// the BMC's MAC restated. Nothing here may promote it to a server UUID.
func TestRedfishServiceUUIDIsNotTheServersUUID(t *testing.T) {
	r := rec("192.0.2.41", "bmc")
	r.Attributes = map[string]string{
		"vendor":      "supermicro",
		"redfishUuid": "00000000-0000-0000-0000-ac1f6b5b46ad",
	}
	if m := Extract(r); m != nil && !m.Empty() {
		t.Fatalf("service root UUID described a managed server: %+v", m)
	}
}

// An unprovisioned FRU answers productName with "NONE", and the model slot used to
// take that literally: a described managed server whose sole property was that its
// model is not set.
func TestPlaceholderModelRejected(t *testing.T) {
	m := Extract(rec("192.0.2.48", "bmc", f("ipmi.postAuth.fru", "productName", "NONE")))
	if m != nil && len(m.Model) != 0 {
		t.Fatalf("model = %+v, want the placeholder dropped", m.Model)
	}
	m = Extract(rec("192.0.2.49", "bmc", f("ipmi.postAuth.fru", "productName", "SYS-2029U-TR4")))
	if m == nil || len(m.Model) != 1 || m.Model[0].Value != "SYS-2029U-TR4" {
		t.Fatalf("real model dropped: %+v", m)
	}
}

// Embedded is what lands on the device's own scan record, so it must not restate what
// that record already says about itself.
func TestEmbeddedDropsTheDevicesOwnIdentity(t *testing.T) {
	m := &ManagedHost{
		BMC: "192.0.2.10", BMCVendor: "hpe", BMCClass: "bmc",
		BMCMACs:    []string{"aa:bb:cc:00:00:13"},
		Neighbours: []Neighbour{{IP: "192.0.2.20", MAC: "aa:bb:cc:00:00:10"}},
		MACs:       []Value{{Value: "aa:bb:cc:00:00:10"}},
		Confidence: Identity,
	}
	e := m.Embedded()
	if e == nil {
		t.Fatal("nil embedded form for a described server")
	}
	if e.BMC != "" || e.BMCVendor != "" || e.BMCClass != "" || e.BMCMACs != nil || e.Neighbours != nil {
		t.Fatalf("embedded form kept the device's own identity: %+v", e)
	}
	if len(e.MACs) != 1 {
		t.Fatalf("embedded form lost the server's NICs: %+v", e)
	}
	if m.BMC == "" || m.Neighbours == nil {
		t.Fatal("Embedded mutated the original")
	}
	if (&ManagedHost{BMC: "192.0.2.11"}).Embedded() != nil {
		t.Fatal("a device that described nothing must have no embedded form")
	}
}
